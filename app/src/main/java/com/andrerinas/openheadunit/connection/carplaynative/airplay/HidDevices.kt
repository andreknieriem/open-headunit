package com.andrerinas.openheadunit.connection.carplaynative.airplay

import com.andrerinas.openheadunit.connection.carplaynative.codec.PlistValue

/**
 * The HID devices that /info announces: touch, knob, media and telephony.
 * Follows LIVI (https://github.com/f-io/LIVI), crate livi-cp, `hid.rs`.
 */
internal object HidDevices {
    const val TOUCH_UID = 0x2a2a2a2aL
    const val KNOB_UID = 0x2a2a2a2bL
    const val MEDIA_UID = 0x2a2a2a2cL
    const val TELEPHONY_UID = 0x2a2a2a2dL
    const val TOUCH_CONTACTS = 2

    /** The touch descriptor for a display of the given size: two finger collections. */
    fun touchDescriptor(xMax: Int, yMax: Int): ByteArray {
        val out = java.io.ByteArrayOutputStream()
        out.write(byteArrayOf(0x05, 0x0d, 0x09, 0x04, 0xa1.toByte(), 0x01))
        repeat(TOUCH_CONTACTS) {
            var axis = 0
            for (b in FINGER) {
                if (b >= 0) {
                    out.write(b)
                } else {
                    val max = if (axis < 2) xMax else yMax
                    out.write(if (axis % 2 == 0) max and 0xff else (max ushr 8) and 0xff)
                    axis++
                }
            }
        }
        out.write(0xc0)
        return out.toByteArray()
    }

    fun touch(xMax: Int, yMax: Int, displayUuid: String, name: String): PlistValue =
        entry(TOUCH_UID, name, touchDescriptor(xMax, yMax), displayUuid)

    fun knob(displayUuid: String, name: String): PlistValue = entry(KNOB_UID, name, bytes(KNOB), displayUuid)
    fun media(displayUuid: String, name: String): PlistValue = entry(MEDIA_UID, name, bytes(MEDIA), displayUuid)
    fun telephony(displayUuid: String, name: String): PlistValue = entry(TELEPHONY_UID, name, bytes(TELEPHONY), displayUuid)

    private fun entry(uid: Long, name: String, descriptor: ByteArray, displayUuid: String): PlistValue = PlistValue.dict(
        "hidProductID" to PlistValue.Integer(1),
        "hidVendorID" to PlistValue.Integer(2),
        "hidCountryCode" to PlistValue.Integer(0),
        "uuid" to PlistValue.Text(java.lang.Long.toHexString(uid)),
        "name" to PlistValue.Text(name),
        "displayUUID" to PlistValue.Text(displayUuid),
        "hidDescriptor" to PlistValue.Data(descriptor),
    )

    private fun bytes(values: IntArray) = ByteArray(values.size) { values[it].toByte() }

    // -1 marks an axis maximum: x low, x high, y low, y high.
    private val FINGER = intArrayOf(
        0x05, 0x0d, 0x09, 0x22, 0xa1, 0x02, 0x09, 0x38, 0x75, 0x08, 0x95, 0x01,
        0x81, 0x02, 0x15, 0x00, 0x25, 0x01, 0x09, 0x33, 0x75, 0x01, 0x95, 0x01,
        0x81, 0x02, 0x95, 0x07, 0x81, 0x03, 0x05, 0x01, 0x26, -1, -1, 0x09,
        0x30, 0x75, 0x10, 0x95, 0x01, 0x81, 0x02, 0x26, -1, -1, 0x09, 0x31,
        0x81, 0x02, 0xc0,
    )
    private val KNOB = intArrayOf(
        0x05, 0x01, 0x09, 0x08, 0xa1, 0x01, 0x05, 0x09, 0x09, 0x01, 0x15, 0x00,
        0x25, 0x01, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02, 0x05, 0x0c, 0x0a, 0x23,
        0x02, 0x0a, 0x24, 0x02, 0x95, 0x02, 0x81, 0x02, 0x95, 0x05, 0x81, 0x01,
        0x05, 0x01, 0x09, 0x01, 0xa1, 0x00, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81,
        0x25, 0x7f, 0x75, 0x08, 0x95, 0x02, 0x81, 0x02, 0xc0, 0x09, 0x38, 0x15,
        0x81, 0x25, 0x7f, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06, 0xc0,
    )
    private val MEDIA = intArrayOf(
        0x05, 0x0c, 0x09, 0x01, 0xa1, 0x01, 0x15, 0x00, 0x25, 0x06, 0x05, 0x0c,
        0x0a, 0x00, 0x00, 0x0a, 0xb0, 0x00, 0x0a, 0xb1, 0x00, 0x0a, 0xcd, 0x00,
        0x0a, 0xb5, 0x00, 0x0a, 0xb6, 0x00, 0x0a, 0x9e, 0x02, 0x75, 0x08, 0x95,
        0x01, 0x81, 0x00, 0xc0,
    )
    private val TELEPHONY = intArrayOf(
        0x05, 0x0b, 0x09, 0x07, 0xa1, 0x01, 0x15, 0x00, 0x25, 0x11, 0x05, 0x0b,
        0x09, 0x00, 0x09, 0x20, 0x09, 0x21, 0x09, 0x26, 0x09, 0x2f, 0x09, 0xb0,
        0x09, 0xb1, 0x09, 0xb2, 0x09, 0xb3, 0x09, 0xb4, 0x09, 0xb5, 0x09, 0xb6,
        0x09, 0xb7, 0x09, 0xb8, 0x09, 0xb9, 0x09, 0xba, 0x09, 0xbb, 0x05, 0x07,
        0x09, 0x2a, 0x75, 0x08, 0x95, 0x01, 0x81, 0x00, 0xc0,
    )
}
